import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:ui_kit/ui_kit.dart';

import '../providers/summary_provider.dart';

class AiSummaryScreen extends ConsumerWidget {
  const AiSummaryScreen({super.key, required this.patientId});

  final String patientId;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final summaryAsync = ref.watch(patientSummaryProvider(patientId));

    return Scaffold(
      appBar: AppBar(
        title: const Text('AI Patient Summary'),
        actions: [
          IconButton(
            icon: const Icon(Icons.refresh),
            tooltip: 'Regenerate summary',
            onPressed: () =>
                ref.invalidate(patientSummaryProvider(patientId)),
          ),
        ],
      ),
      body: summaryAsync.when(
        data: (summary) => SingleChildScrollView(
          padding: AppSpacing.screenPadding,
          child: Center(
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxWidth: 720),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  // Summary header
                  Row(
                    children: [
                      Icon(
                        Icons.auto_awesome,
                        color: AppColors.primary,
                        size: 28,
                      ),
                      const SizedBox(width: AppSpacing.sm),
                      Text('Patient Summary', style: AppTypography.h2),
                    ],
                  ),
                  const SizedBox(height: AppSpacing.sm),
                  Text(
                    'Generated by AI based on the patient\'s complete medical history.',
                    style: AppTypography.bodySmall,
                  ),
                  const SizedBox(height: AppSpacing.lg),

                  // Summary text
                  HosCard(
                    child: Padding(
                      padding: AppSpacing.cardPadding,
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('Overview', style: AppTypography.h4),
                          const SizedBox(height: AppSpacing.sm),
                          Text(
                            summary.summary,
                            style: AppTypography.bodyMedium,
                          ),
                        ],
                      ),
                    ),
                  ),
                  const SizedBox(height: AppSpacing.md),

                  // Key Findings
                  if (summary.keyFindings.isNotEmpty) ...[
                    _SummarySection(
                      icon: Icons.search,
                      title: 'Key Findings',
                      items: summary.keyFindings,
                      color: AppColors.info,
                    ),
                    const SizedBox(height: AppSpacing.md),
                  ],

                  // Risk Factors
                  if (summary.riskFactors.isNotEmpty) ...[
                    _SummarySection(
                      icon: Icons.warning_amber_rounded,
                      title: 'Risk Factors',
                      items: summary.riskFactors,
                      color: AppColors.warning,
                    ),
                    const SizedBox(height: AppSpacing.md),
                  ],

                  // Recommendations
                  if (summary.recommendations.isNotEmpty) ...[
                    _SummarySection(
                      icon: Icons.lightbulb_outline,
                      title: 'Recommendations',
                      items: summary.recommendations,
                      color: AppColors.success,
                    ),
                    const SizedBox(height: AppSpacing.md),
                  ],

                  // Disclaimer
                  Container(
                    padding: AppSpacing.cardPadding,
                    decoration: BoxDecoration(
                      color: AppColors.warning.withOpacity(0.08),
                      borderRadius:
                          BorderRadius.circular(AppSpacing.borderRadius),
                      border: Border.all(
                        color: AppColors.warning.withOpacity(0.3),
                      ),
                    ),
                    child: Row(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Icon(
                          Icons.info_outline,
                          size: 18,
                          color: AppColors.warning,
                        ),
                        const SizedBox(width: AppSpacing.sm),
                        Expanded(
                          child: Text(
                            'This summary is AI-generated and should be used as a reference only. '
                            'Always verify findings with the patient\'s actual records.',
                            style: AppTypography.bodySmall.copyWith(
                              color: AppColors.textSecondary,
                            ),
                          ),
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: AppSpacing.xl),
                ],
              ),
            ),
          ),
        ),
        loading: () => Center(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const HosLoading(),
              const SizedBox(height: AppSpacing.md),
              Text(
                'Generating AI summary...',
                style: AppTypography.bodyMedium.copyWith(
                  color: AppColors.textSecondary,
                ),
              ),
              const SizedBox(height: AppSpacing.xs),
              Text(
                'This may take a few moments.',
                style: AppTypography.bodySmall,
              ),
            ],
          ),
        ),
        error: (error, _) => HosError(
          message: 'Failed to generate AI summary',
          onRetry: () =>
              ref.invalidate(patientSummaryProvider(patientId)),
        ),
      ),
    );
  }
}

class _SummarySection extends StatelessWidget {
  const _SummarySection({
    required this.icon,
    required this.title,
    required this.items,
    required this.color,
  });

  final IconData icon;
  final String title;
  final List<String> items;
  final Color color;

  @override
  Widget build(BuildContext context) {
    return HosCard(
      child: Padding(
        padding: AppSpacing.cardPadding,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Icon(icon, size: 20, color: color),
                const SizedBox(width: AppSpacing.sm),
                Text(title, style: AppTypography.h4),
              ],
            ),
            const SizedBox(height: AppSpacing.sm),
            ...items.map(
              (item) => Padding(
                padding: const EdgeInsets.only(bottom: AppSpacing.xs),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Padding(
                      padding: const EdgeInsets.only(top: 6),
                      child: Icon(
                        Icons.circle,
                        size: 6,
                        color: color,
                      ),
                    ),
                    const SizedBox(width: AppSpacing.sm),
                    Expanded(
                      child: Text(item, style: AppTypography.bodyMedium),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}
